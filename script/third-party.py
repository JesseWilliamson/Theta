#!/usr/bin/env python3
"""Regenerates docs/THIRD_PARTY.md: the direct dependencies of every workspace crate with their
licences, taken from `cargo metadata` (so it covers every target platform, not just this one).

    script/third-party.py            # rewrites docs/THIRD_PARTY.md
    script/third-party.py --check    # exits 1 if the file is stale

Licence strings are the crates' own `license` fields (SPDX expressions); a crate that only ships
a `license-file` is listed as such. Copyleft or missing licences are called out at the top.
"""
import json
import os
import re
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root))
pkgs = {p["id"]: p for p in meta["packages"]}
members = set(meta["workspace_members"])
resolve = {n["id"]: n for n in meta["resolve"]["nodes"]}

# Direct dependencies of workspace members that are not workspace members themselves.
direct = {}
for m in members:
    for dep in resolve[m]["deps"]:
        if dep["pkg"] in members:
            continue
        p = pkgs[dep["pkg"]]
        direct.setdefault(p["name"], {})[p["version"]] = p
        direct[p["name"]][p["version"]]["_users"] = direct[p["name"]][p["version"]].get("_users", set()) | {
            pkgs[m]["name"]}

COPYLEFT = re.compile(r"\b(A?GPL|LGPL|MPL|EPL|CDDL|CC-BY-SA|OSL|EUPL|SSPL)", re.I)

def lic(p):
    if p.get("license"):
        return p["license"].replace("/", " OR ")
    if p.get("license_file"):
        return f"see {p['license_file']}"
    return "UNKNOWN"

def flags(l):
    # An OR expression is fine if one branch is permissive; flag only when every branch is.
    if l == "UNKNOWN" or l.startswith("see "):
        return "unknown"
    alts = re.split(r"\s+OR\s+", re.sub(r"[()]", "", l))
    if all(COPYLEFT.search(a) for a in alts):
        return "copyleft"
    if any(COPYLEFT.search(a) for a in alts):
        return "weak (permissive alternative exists)"
    return ""

rows, flagged = [], []
for name in sorted(direct, key=str.lower):
    for ver in sorted(direct[name]):
        p = direct[name][ver]
        l = lic(p)
        f = flags(l)
        rows.append((name, ver, l, ", ".join(sorted(p["_users"])), p.get("repository") or p.get("homepage") or ""))
        if f:
            flagged.append((name, ver, l, f))

out = ["# Third-party dependencies", "",
       "Generated by `script/third-party.py` from `cargo metadata` (all target platforms). Do not edit by hand.",
       "This lists the *direct* dependencies of Theta's crates; their own dependencies are in `Cargo.lock`.",
       "Bundled non-Rust assets (fonts, themes) are credited in `crates/theta-ui/NOTICE`.",
       "",
       "The letterform of Theta's logo is the theta (U+03B8) of **GFS Didot**: Copyright (c) 2007 Greek Font Society",
       "(www.greekfontsociety.org), with Reserved Font Name 'GFS Didot', licensed under the SIL Open Font License 1.1",
       "(`crates/theta-ui/assets/fonts/GFSDidot-OFL.txt`). Its outline is embedded as path data in",
       "`packaging/icons/gen_icon.py`; the font file is not bundled or needed to build.", ""]
out.append("## Licence review")
out.append("")
if flagged:
    for n, v, l, f in flagged:
        out.append(f"- **{n} {v}**: `{l}` ({f})")
else:
    out.append("No direct dependency is copyleft or has an unknown licence.")
# Transitive crates (the whole lockfile, all platforms) that need a closer look.
direct_ids = {p["id"] for n in direct for p in direct[n].values()}
notable = []
for p in meta["packages"]:
    if p["id"] in members or p["id"] in direct_ids:
        continue
    l = lic(p)
    if flags(l) in ("unknown", "copyleft") or re.search(r"MPL|CDLA", l):
        notable.append((p["name"], p["version"], l))
out += ["", "## Transitive crates worth a look", "",
        "Pulled in indirectly (some only on one platform or as build tools). MPL-2.0 is file-level copyleft:",
        "unmodified use as a dependency is unproblematic but its notices must travel with source distributions.", ""]
for n, v, l in sorted(set(notable), key=lambda x: x[0].lower()):
    out.append(f"- {n} {v}: `{l}`")
out += ["", "## Direct dependencies", "", "| Crate | Version | Licence | Used by | Source |", "| --- | --- | --- | --- | --- |"]
for n, v, l, u, r in rows:
    out.append(f"| {n} | {v} | {l} | {u} | {r} |")
text = "\n".join(out) + "\n"

path = os.path.join(root, "docs", "THIRD_PARTY.md")
if "--check" in sys.argv:
    sys.exit(0 if os.path.exists(path) and open(path).read() == text else 1)
open(path, "w").write(text)
print(f"wrote {path}: {len(rows)} crates, {len(flagged)} flagged")
