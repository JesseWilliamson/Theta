"""Generate the table-driven Rust tests under src/tests/vim_*.rs from real Vim.

    ./gen_dsl_tests.py            # rewrites ../../src/tests/vim_<area>.rs

Every case is `(name, before, keys)`; the expected state is whatever Vim ends up with, rendered in the
DSL of src/tests/vim_dsl.rs (`[x]` is the cursor on x, `[]` on an empty line). The files are generated:
change the tables below, not the output. Cases that Vim itself rejects or that need things Vim cannot
do (clipboard, host effects, the leader menu, `gc`) are written by hand in src/tests/vim_*.rs instead.
"""
import os
