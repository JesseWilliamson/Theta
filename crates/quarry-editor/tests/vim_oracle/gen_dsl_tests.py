OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "tests")
AREAS = {}


def area(name, doc):
    AREAS[name] = {"doc": doc, "cases": []}
    return AREAS[name]["cases"]


def slug(keys):
    names = {"<esc>": "esc", "<ret>": "ret", "<tab>": "tab", "<bs>": "bs", "<lt>": "lt", "<C-": "c", "<space>": "sp"}
    s = keys
    for k, v in names.items():
        s = s.replace(k, "_" + v + "_")
    out = []
    for ch in s:
        if ch.isalnum():
            out.append(ch)
        else:
            out.append({"$": "S", "^": "K", "%": "P", "*": "A", "#": "H", "(": "lp", ")": "rp", "{": "lb", "}": "rb", "[": "ls", "]": "rs", "\"": "dq",
                        "'": "sq", "`": "bq", ".": "dot", ",": "cm", ";": "sc", ":": "co", "/": "sl", "?": "qm", "<": "lt", ">": "gt", "~": "tl", "-": "mi",
                        "+": "pl", "_": "u", "|": "bar", "&": "amp", "=": "eq", "!": "bang", " ": "sp", "@": "at", "\\": "bs"}.get(ch, "x"))
    r = re.sub(r"_+", "_", "".join(out)).strip("_")
    return r[:40] or "k"


def rs(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def render(text, line, col, markers):
    """DSL text for Vim's result: cursor marker at (line, byte col)."""
    o, c = markers
    lines = text.split("\n")
    off = 0
    for i in range(line - 1):
        off += len(lines[i]) + 1
    cur = lines[line - 1] if line - 1 < len(lines) else ""
    b = cur.encode()[: max(col - 1, 0)]
    idx = off + len(b.decode(errors="ignore"))
    ch = text[idx] if idx < len(text) else ""
    if ch and ch not in "\n\r":
        return text[:idx] + o + ch + c + text[idx + 1:]
    return text[:idx] + o + c + text[idx:]


def run_case(before, keys):
    if keys.startswith(":") and "<ret>" not in keys:
        return oracle.run(before, keys, regs=(), ex=keys[1:])
    return oracle.run(before, keys, regs=())


def gen():
    for name, a in AREAS.items():
        seen = {}
        lines = []
        for case in a["cases"]:
            cname, before, keys = case
            base = cname or slug(keys)
            n = seen.get(base, 0)
            seen[base] = n + 1
            fn = base if n == 0 else "%s_%d" % (base, n + 1)
            if fn[0].isdigit():
                fn = "k" + fn
            try:
                r = run_case(before, keys)
            except Exception as e:  # Vim hung or died: leave the case out
                print("skipped %r %r: %s" % (before, keys, type(e).__name__), file=sys.stderr)
                continue
            markers = ("‹", "›") if "‹" in before else ("[", "]")
            after = render(r["text"], r["line"], r["col"], markers)
            if "[" in r["text"] and markers[0] == "[":
                markers = ("‹", "›")
                after = render(r["text"], r["line"], r["col"], markers)
                if "‹" not in before:
                    # the before text needs the other markers too
                    before = before.replace("[", "‹", 1).replace("]", "›", 1)
            kk = keys.replace("\u00a6", "")
            if kk.startswith(":") and "<ret>" not in kk:
                kk += "<ret>"
            lines.append("    v_%s: %s, %s => %s;" % (fn, rs(before), rs(kk), rs(after)))
        path = os.path.join(OUT, "vim_%s.rs" % name)
        with open(path, "w", encoding="utf-8") as f:
            f.write("//! %s\n//!\n//! Generated by tests/vim_oracle/gen_dsl_tests.py from real Vim: edit the tables there.\n\n" % a["doc"])
            f.write("use super::*;\n\nvim_cases! {\n")
            f.write("\n".join(lines))
            f.write("\n}\n")
        print("%s: %d cases" % (path, len(lines)))


