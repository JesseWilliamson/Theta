//! The catalog facts a faithful ALTER needs: identity, generated columns, checks, unique constraints,
//! partial and expression indexes, deferrable foreign keys, view definitions, table options.

mod common;

use common::*;
use theta_core::*;

fn table<'a>(c: &'a Catalog, schema: &str, name: &str) -> &'a Table {
    c.find_table(Some(schema), name).unwrap_or_else(|| panic!("{schema}.{name} not in the catalog")).1
}

fn col<'a>(t: &'a Table, name: &str) -> &'a ColumnInfo {
    t.columns.iter().find(|c| c.name == name).unwrap_or_else(|| panic!("column {name}"))
}

#[tokio::test]
async fn postgres_extras() {
    let fx = PgFx::new().await;
    let c = fx.conn.as_ref();
    run(c, "CREATE TABLE parent (id integer PRIMARY KEY)").await;
    run(
        c,
        "CREATE TABLE t (\
           id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, \
           alt integer GENERATED BY DEFAULT AS IDENTITY, \
           price numeric(10,2) NOT NULL CHECK (price > 0), \
           qty integer NOT NULL DEFAULT 1, \
           total numeric GENERATED ALWAYS AS (price * qty) STORED, \
           email text, \
           parent_id integer CONSTRAINT t_parent_fk REFERENCES parent(id) DEFERRABLE INITIALLY DEFERRED, \
           CONSTRAINT email_unique UNIQUE (email), \
           CONSTRAINT qty_nonneg CHECK (qty >= 0))",
    )
    .await;
    run(c, "CREATE INDEX t_active ON t (lower(email)) WHERE qty > 0").await;
    run(c, "CREATE VIEW v AS SELECT id, price FROM t").await;
    let cat = c.introspect().await.unwrap();
    let t = table(&cat, &fx.schema, "t");
    assert_eq!(col(t, "id").identity, Some(Identity::Always));
    assert_eq!(col(t, "alt").identity, Some(Identity::ByDefault));
    assert_eq!(col(t, "qty").identity, None);
    let total = col(t, "total");
    assert_eq!(
        total.generated,
        Some(GeneratedColumn { expression: "(price * (qty)::numeric)".into(), stored: true })
    );
    assert_eq!(total.default, None);
    let mut checks: Vec<(&str, &str)> =
        t.checks.iter().map(|c| (c.name.as_str(), c.expression.as_str())).collect();
    checks.sort();
    assert_eq!(checks, vec![("qty_nonneg", "qty >= 0"), ("t_price_check", "price > 0::numeric")]);
    assert_eq!(
        t.unique_constraints,
        vec![UniqueConstraint { name: "email_unique".into(), columns: vec!["email".into()] }]
    );
    let fk = &t.foreign_keys[0];
    assert!(fk.deferrable && fk.initially_deferred, "{fk:?}");
    let idx = t.indexes.iter().find(|i| i.name == "t_active").unwrap();
    assert_eq!(idx.predicate.as_deref(), Some("(qty > 0)"));
    assert!(idx.has_expressions);
    let v = table(&cat, &fx.schema, "v");
    assert!(v.view_definition.as_deref().unwrap().contains("FROM t"), "{:?}", v.view_definition);
    assert!(table(&cat, &fx.schema, "parent").view_definition.is_none());
    fx.done().await;
}

#[tokio::test]
async fn mysql_extras() {
    let fx = MyFx::new().await;
    let c = fx.conn.as_ref();
    run(
        c,
        "CREATE TABLE t (\
           id int NOT NULL AUTO_INCREMENT PRIMARY KEY, \
           price decimal(10,2) NOT NULL, \
           qty int NOT NULL DEFAULT 1, \
           total decimal(12,2) GENERATED ALWAYS AS (price * qty) STORED, \
           label varchar(20) GENERATED ALWAYS AS (concat('#', id)) VIRTUAL, \
           email varchar(100), \
           CONSTRAINT email_unique UNIQUE (email), \
           CONSTRAINT price_pos CHECK (price > 0)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4",
    )
    .await;
    run(c, "CREATE VIEW v AS SELECT id, price FROM t").await;
    let cat = c.introspect().await.unwrap();
    let t = table(&cat, &fx.db, "t");
    assert_eq!(col(t, "id").identity, Some(Identity::ByDefault));
    assert!(
        col(t, "total").generated.as_ref().is_some_and(|g| g.stored && g.expression.contains("price")),
        "{:?}",
        col(t, "total")
    );
    assert!(col(t, "label").generated.as_ref().is_some_and(|g| !g.stored));
    assert_eq!(t.unique_constraints.len(), 1);
    assert_eq!(t.unique_constraints[0].name, "email_unique");
    assert_eq!(t.unique_constraints[0].columns, vec!["email".to_string()]);
    assert!(
        t.checks.iter().any(|c| c.name == "price_pos" && c.expression.contains("price")),
        "{:?}",
        t.checks
    );
    let opts: Vec<(&str, &str)> = t.options.iter().map(|o| (o.name.as_str(), o.value.as_str())).collect();
    assert!(opts.contains(&("ENGINE", "InnoDB")), "{opts:?}");
    assert!(opts.iter().any(|(k, v)| *k == "CHARSET" && *v == "utf8mb4"), "{opts:?}");
    let v = table(&cat, &fx.db, "v");
    assert!(
        v.view_definition.as_deref().is_some_and(|d| d.to_lowercase().contains("select")),
        "{:?}",
        v.view_definition
    );
    fx.done().await;
}

#[tokio::test]
async fn sqlite_extras() {
    let c = theta_drivers::connect(&sqlite_config(":memory:")).await.unwrap();
    let c = c.as_ref();
    run(
        c,
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, price REAL NOT NULL CHECK (price > 0), qty INT DEFAULT 1, \
           total REAL GENERATED ALWAYS AS (price * qty) STORED, double_it INT AS (qty * 2), email TEXT, \
           CONSTRAINT qty_ok CHECK (qty >= 0), UNIQUE (email))",
    )
    .await;
    run(c, "CREATE INDEX t_part ON t (qty) WHERE qty > 0").await;
    run(c, "CREATE VIEW v AS SELECT id, price FROM t").await;
    run(c, "CREATE TABLE plain (a INTEGER PRIMARY KEY, b TEXT)").await;
    let cat = c.introspect().await.unwrap();
    let t = table(&cat, "main", "t");
    assert_eq!(col(t, "id").identity, Some(Identity::ByDefault));
    assert_eq!(
        col(t, "total").generated,
        Some(GeneratedColumn { expression: "price * qty".into(), stored: true })
    );
    assert_eq!(
        col(t, "double_it").generated,
        Some(GeneratedColumn { expression: "qty * 2".into(), stored: false })
    );
    assert_eq!(t.checks.len(), 2, "{:?}", t.checks);
    assert!(t.checks.iter().any(|c| c.name == "qty_ok" && c.expression == "qty >= 0"));
    assert_eq!(t.unique_constraints.len(), 1);
    assert_eq!(t.unique_constraints[0].columns, vec!["email".to_string()]);
    let part = t.indexes.iter().find(|i| i.name == "t_part").unwrap();
    assert_eq!(part.predicate.as_deref(), Some("qty > 0"));
    assert!(table(&cat, "main", "v").view_definition.as_deref().is_some_and(|d| d.starts_with("SELECT")));
    // A lone INTEGER PRIMARY KEY numbers itself even without AUTOINCREMENT.
    assert_eq!(col(table(&cat, "main", "plain"), "a").identity, Some(Identity::ByDefault));
    assert_eq!(col(table(&cat, "main", "plain"), "b").identity, None);
}
