#!/usr/bin/env python3
"""Single source for the theta mark on the website.

The drawings live in packaging/icons/gen_icon.py (the app icon, the in-app mark and this site all
come from it), and this module imports them, so the site and the app cannot drift. It derives:

  * `sprite()`        two <symbol>s that build_pages.py puts in every page, drawn with
                      <use href="#theta"> inside an <svg> sized by CSS:
                        #theta       the medium-weight drawing (the app's in-app mark): nav, footer and
                                     the small eyebrow mark, 12 to 26 px tall, where the approved
                                     hairlines (2% of the height) would be thinner than a pixel;
                        #theta-fine  the approved delicate drawing (hairline top and bottom, bar with
                                     bracketed serifs): the large marks (why-theta section, 404 page)
                                     and the social card.
  * assets/theta-mark.svg   a standalone copy of the delicate drawing (currentColor).
  * assets/favicon.svg      the 32 px pixel-grid app icon (tile included; a favicon cannot inherit colour).
  * tools/og.html           the delicate mark in the social card, between the `mark` markers.

Both symbols have the same tight 46 x 76 viewBox (the bowl's bounding box), so CSS sizes them alike.
The mark is filled shapes only: there is no stroke width to tune per size, which the previous
line-art mark needed a CSS variable for.

usage: mark.py          rewrite the derived files
       mark.py --check  exit 1 if any derived file is out of date (used by check.mjs)
"""
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SITE.parent / "packaging" / "icons"))
import gen_icon as g  # noqa: E402

# The approved drawing in the bowl's own units (the app icon applies a scale on top of it).
FINE = {**g.FULL, "u": 1.0}
BOX_W, BOX_H = 2 * g.MARK["rx"], 2 * g.MARK["ry"]
VIEWBOX = f"0 0 {g.fmt(BOX_W)} {g.fmt(BOX_H)}"
NOTE = "<!-- Generated by site/tools/mark.py from packaging/icons/gen_icon.py; do not edit. -->"


def _shapes(D):
    return g.shapes(D, BOX_W / 2, BOX_H / 2)


def sprite():
    """The two <symbol>s for the hidden sprite."""
    return (f'<symbol id="theta" viewBox="{VIEWBOX}">{_shapes(g.MARK)}</symbol>'
            f'<symbol id="theta-fine" viewBox="{VIEWBOX}">{_shapes(FINE)}</symbol>')


def standalone():
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX}" width="{g.fmt(BOX_W)}" height="{g.fmt(BOX_H)}">\n'
            f'  {NOTE}\n  <title>Theta</title>\n  {_shapes(FINE)}\n</svg>\n')


def favicon():
    return g.svg_tile(g.MID, g.DARK_BG, highlight=False).replace("<title>", NOTE + "\n  <title>", 1)


OG = SITE / "tools" / "og.html"
OG_RE = re.compile(r"<!--mark-->.*?<!--/mark-->", re.S)


def og_html():
    svg = f'<svg viewBox="{VIEWBOX}">{_shapes(FINE)}</svg>'
    return OG_RE.sub(lambda _: f"<!--mark-->{svg}<!--/mark-->", OG.read_text())


def outputs():
    return {SITE / "assets" / "theta-mark.svg": standalone(), SITE / "assets" / "favicon.svg": favicon(), OG: og_html()}


def main():
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if "--check" not in sys.argv:
                path.write_text(text)
    if "--check" in sys.argv:
        for p in stale:
            print("out of date:", p.relative_to(SITE.parent))
        sys.exit(1 if stale else 0)
    print("synced:", ", ".join(p.name for p in stale) or "nothing to do")


if __name__ == "__main__":
    main()
