#!/usr/bin/env python3
"""Single source for the theta mark on the website.

The geometry lives in packaging/icons/theta-mark.svg, which gen_icon.py writes and the app embeds.
This module reads it and derives everything the site draws, so the site and the app cannot drift:

  * `sprite()`        the <symbol id="theta"> that build_pages.py puts in every page; pages draw it with
                      <use href="#theta"> inside an <svg> sized by CSS.
  * assets/theta-mark.svg   a standalone copy of the same drawing (currentColor).
  * assets/favicon.svg      the mark in white on the app's dark tile (a favicon cannot inherit colour).
  * tools/og.html           the mark in the social card, between the `mark` markers.

usage: sync_mark.py          rewrite the derived files
       sync_mark.py --check  exit 1 if any derived file is out of date (used by check.mjs)

Stroke widths stay in the source's units (the tight viewBox is about 216 wide). CSS can thin a large
mark with `--mark-w`; the bar keeps the source's bar-to-ring ratio.
"""
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
SOURCE = SITE.parent / "packaging" / "icons" / "theta-mark.svg"


def _num(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def load():
    """Parse the source: ring path, bar path and stroke widths, plus the tight viewBox around them."""
    text = SOURCE.read_text()
    g = re.search(r'<g transform="translate\(([-\d.]+) ([-\d.]+)\)"([^>]*)>(.*)</g>', text, re.S)
    tx, ty = float(g.group(1)), float(g.group(2))
    sw = float(re.search(r'stroke-width="([\d.]+)"', g.group(3)).group(1))
    paths = re.findall(r'<path d="([^"]+)"(?: stroke-width="([\d.]+)")?', g.group(4))
    assert len(paths) == 2, "expected a ring and a bar"
    (ring, _), (bar, bar_sw) = paths
    bar_sw = float(bar_sw or sw)
    pts = [(float(x), float(y)) for p in (ring, bar) for x, y in re.findall(r"(-?[\d.]+) (-?[\d.]+)", p)]
    half = sw / 2
    x0, x1 = min(x for x, _ in pts) - half + tx, max(x for x, _ in pts) + half + tx
    y0, y1 = min(y for _, y in pts) - half + ty, max(y for _, y in pts) + half + ty
    return dict(ring=ring, bar=bar, sw=sw, bar_sw=bar_sw, tx=tx, ty=ty, box=(x0, y0, x1 - x0, y1 - y0))


def _shapes(m, sw_expr, bar_expr):
    return (f'<g transform="translate({_num(m["tx"] - m["box"][0])} {_num(m["ty"] - m["box"][1])})" fill="none" '
            f'stroke="currentColor" stroke-linejoin="round" stroke-linecap="butt">'
            f'<path d="{m["ring"]}" style="stroke-width:{sw_expr}"/><path d="{m["bar"]}" style="stroke-width:{bar_expr}"/></g>')


def _widths(m):
    sw = _num(m["sw"])
    return f"var(--mark-w,{sw})", f"calc(var(--mark-w,{sw})*{_num(m['bar_sw'] / m['sw'])})"


def viewbox(m=None):
    m = m or load()
    return "0 0 " + " ".join(_num(v) for v in m["box"][2:])


def sprite():
    """<symbol> for the hidden sprite. The geometry is moved so the viewBox starts at 0 0."""
    m = load()
    return f'<symbol id="theta" viewBox="{viewbox(m)}">{_shapes(m, *_widths(m))}</symbol>'


def standalone():
    m = load()
    w, h = m["box"][2:]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox(m)}" width="{_num(w)}" height="{_num(h)}">\n'
            f'  <!-- Generated by site/tools/sync_mark.py from packaging/icons/theta-mark.svg; do not edit. -->\n'
            f'  <title>Theta</title>\n  {_shapes(m, _num(m["sw"]), _num(m["bar_sw"]))}\n</svg>\n')


def favicon():
    """White mark on the app's dark tile. Scaled so the ring is 64% of the tile's height, like the app icon."""
    m = load()
    w, h = m["box"][2:]
    k = 64 * 0.64 / h
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n'
            f'  <!-- Generated by site/tools/sync_mark.py from packaging/icons/theta-mark.svg; do not edit. -->\n'
            f'  <rect width="64" height="64" rx="14" fill="#21252b"/>\n'
            f'  <g transform="translate({_num(32 - w * k / 2)} {_num(32 - h * k / 2)}) scale({_num(k)})" color="#ffffff">'
            f'{_shapes(m, _num(m["sw"] * 1.15), _num(m["bar_sw"] * 1.15))}</g>\n</svg>\n')


OG = SITE / "tools" / "og.html"
OG_RE = re.compile(r"<!--mark-->.*?<!--/mark-->", re.S)


def og_html():
    m = load()
    svg = f'<svg viewBox="{viewbox(m)}">{_shapes(m, _num(m["sw"] * 0.55), _num(m["bar_sw"] * 0.55))}</svg>'
    return OG_RE.sub(lambda _: f"<!--mark-->{svg}<!--/mark-->", OG.read_text())


def outputs():
    return {SITE / "assets" / "theta-mark.svg": standalone(), SITE / "assets" / "favicon.svg": favicon(), OG: og_html()}


def main():
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if "--check" not in sys.argv:
                path.write_text(text)
    if "--check" in sys.argv:
        for p in stale:
            print("out of date:", p.relative_to(SITE.parent))
        sys.exit(1 if stale else 0)
    print("synced:", ", ".join(p.name for p in stale) or "nothing to do")


if __name__ == "__main__":
    main()
